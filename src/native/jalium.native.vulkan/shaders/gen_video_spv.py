#!/usr/bin/env python3
"""Rebuild the combined immutable-sampler video fragment shader (build tool only)."""
import pathlib
import struct
import subprocess
import tempfile

root = pathlib.Path(__file__).resolve().parent
with tempfile.TemporaryDirectory() as directory:
    lines = ["// Generated by shaders/gen_video_spv.py. Do not edit.", "#pragma once",
             "#include <cstdint>", "#include <cstddef>", "namespace jalium {"]
    variants = [
        ("kVideoQuadFragSpv", "bitmap_quad.frag.hlsl", ["-D", "--hlsl-dx9-compatible", "-DJALIUM_VIDEO_YCBCR", "-S", "frag", "-e", "main"]),
        ("kVideoReadbackVertSpv", "video_readback.vert", []),
        ("kVideoReadbackFragSpv", "video_readback.frag", []),
    ]
    for name, source, flags in variants:
        output = pathlib.Path(directory) / f"{name}.spv"
        subprocess.run(["glslangValidator", "-V", "--target-env", "vulkan1.0", *flags,
                        str(root / source), "-o", str(output)], check=True)
        subprocess.run(["spirv-val", "--target-env", "vulkan1.0", str(output)], check=True)
        data = output.read_bytes()
        words = struct.unpack(f"<{len(data) // 4}I", data)
        lines += [f"inline constexpr uint32_t {name}[] = {{"]
        lines += ["    " + ", ".join(f"0x{word:08x}" for word in words[i:i+8]) + ","
                  for i in range(0, len(words), 8)]
        lines += ["};", f"inline constexpr size_t {name}Size = sizeof({name});"]
    lines += ["}", ""]
    (root.parent / "include" / "vulkan_video_shaders.h").write_text("\n".join(lines))
