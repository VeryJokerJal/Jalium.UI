#!/usr/bin/env python3
"""Generate P2/P3 strong direction data from pinned Unicode 17 Bidi_Class."""
from pathlib import Path
import hashlib,json,re
root=Path(__file__).resolve().parents[1];base=root/'tools/unicode-bidi-17'
manifest=json.loads((base/'UPSTREAM.json').read_text());assert manifest['unicode_version']=='17.0.0'
source=base/'DerivedBidiClass.txt';assert hashlib.sha256(source.read_bytes()).hexdigest()==manifest['sha256']
values=bytearray(0x110000)
def put(limits,prop):
 a=limits.split('..');first,last=int(a[0],16),int(a[-1],16)
 value=1 if prop in ['L','Left_To_Right']else 2 if prop in ['R','AL','Right_To_Left','Arabic_Letter']else 0
 values[first:last+1]=bytes([value])*(last-first+1)
lines=source.read_text().splitlines()
for line in lines:
 m=re.search(r'@missing:\s*([0-9A-F.]+);\s*(\w+)',line)
 if m:put(*m.groups())
for line in lines:
 text=line.split('#',1)[0].strip()
 if text:put(*(part.strip()for part in text.split(';')))
ends=[];first=0
for cp in range(1,len(values)+1):
 if cp==len(values)or values[cp]!=values[first]:
  ends.append(((cp-1)<<2)|values[first]);first=cp
text='// Generated by tools/generate-css-bidi-direction.py; Unicode 17.0.0.\n// Unicode-3.0 license: tools/unicode-bidi-17/UNICODE-LICENSE.txt.\nnamespace Jalium.UI.Styling;\n\ninternal static class CssBidiDirectionData\n{\n    // Inclusive range end, followed by 0=non-strong, 1=L, 2=R/AL.\n    internal static ReadOnlySpan<uint> Ranges =>\n    [\n'
for at in range(0,len(ends),8):text+='        '+', '.join(f'0x{v:X}'for v in ends[at:at+8])+',\n'
text+='    ];\n}\n'
(root/'src/managed/Jalium.UI.Core/Css/CssBidiDirectionData.cs').write_text(text)
print(len(ends),'strong-direction ranges')
