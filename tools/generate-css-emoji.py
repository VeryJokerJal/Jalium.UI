"""Generate shared CSS emoji presentation sets from pinned Unicode 18 inputs.

The two input files can be supplied offline with --data-dir. No runtime Unicode
package or network dependency is introduced. The existing Unicode license under
src/native/thirdparty applies to these generated tables.
"""
from pathlib import Path
import argparse, hashlib, re, urllib.request

VERSION = "18.0.0"
BASE = f"https://www.unicode.org/Public/{VERSION}/ucd/emoji/"
HASHES = {
    "emoji-variation-sequences.txt": "ff1707564aa1f1b2fcf4ec92d609d4cb26940bc0d4dcf07f5328ad6879e84da3",
    "emoji-data.txt": "80d00f8e616a0ef27fd6b8de3b758c06383b5d917e2977709578e68baf733bf1",
}
ROOT = Path(__file__).resolve().parents[1]

def ranges(values):
    result = []
    for value in sorted(values):
        if result and value == result[-1][1] + 1: result[-1] = result[-1][0], value
        else: result.append((value, value))
    return result

def generate(sources):
    for name, data in sources.items():
        if hashlib.sha256(data).hexdigest() != HASHES[name]: raise ValueError(f"Unexpected Unicode {VERSION} input: {name}")
    participating = {int(m[1],16) for m in re.finditer(r"^([0-9A-F]+) FE0[EF]\s*;",sources['emoji-variation-sequences.txt'].decode(),re.M)}
    defaults = set()
    for match in re.finditer(r"^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*; Emoji_Presentation\s*#",sources['emoji-data.txt'].decode(),re.M):
        defaults.update(range(int(match[1],16),int(match[2] or match[1],16)+1))
    assert participating and defaults
    sets = {'Participating': participating, 'DefaultEmoji': participating & defaults}
    comments = [f"// Generated by tools/generate-css-emoji.py. Unicode {VERSION}. Do not edit.",
        "// Unicode data copyright 2026 Unicode, Inc. https://www.unicode.org/terms_of_use.html",
        *[f"// SHA-256 {name}: {digest}" for name,digest in HASHES.items()]]
    native = comments + ['#pragma once','#include <cstddef>','#include <cstdint>','namespace jalium::emoji_data {','struct Range { uint32_t first, last; };']
    managed = comments + ['namespace Jalium.UI.Styling;','internal static class CssEmojiData','{',f'    internal const string Version = "{VERSION}";']
    for name, values in sets.items():
        pairs = ranges(values)
        native += [f'inline constexpr Range {name}[] = {{']
        managed += [f'    private static readonly int[] {name}Ranges = [']
        for i in range(0,len(pairs),4):
            native += ['    '+' '.join(f'{{0x{a:X}, 0x{b:X}}},' for a,b in pairs[i:i+4])]
            managed += ['        '+' '.join(f'0x{a:X}, 0x{b:X},' for a,b in pairs[i:i+4])]
        native += ['};']
        managed += ['    ];',f'    internal static bool Is{name}(int scalar) => Contains({name}Ranges, scalar);']
    native += ['template<size_t N> inline bool Contains(const Range (&ranges)[N], uint32_t scalar) {',
        '    size_t first=0, last=N; while(first<last) { size_t mid=first+(last-first)/2;',
        '        if(scalar<ranges[mid].first) last=mid; else if(scalar>ranges[mid].last) first=mid+1; else return true;',
        '    } return false;', '}',
        '// Only Unicode Emoji Presentation Participating Code Points are affected.',
        'inline uint16_t Selector(uint32_t scalar, uint32_t variant) {',
        '    if(!variant || !Contains(Participating,scalar)) return 0;',
        '    return variant==1 ? 0xFE0E : variant==2 ? 0xFE0F : Contains(DefaultEmoji,scalar) ? 0xFE0F : 0xFE0E;',
        '}', '}']
    managed += ['    private static bool Contains(int[] ranges, int scalar)','    {',
        '        int first=0, last=ranges.Length/2; while(first<last) { int mid=first+(last-first)/2;',
        '            if(scalar<ranges[mid*2]) last=mid; else if(scalar>ranges[mid*2+1]) first=mid+1; else return true;',
        '        } return false;', '    }', '}']
    return '\n'.join(native)+'\n','\n'.join(managed)+'\n',sets

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--data-dir',type=Path)
    parser.add_argument('--native-out',type=Path,default=ROOT/'src/native/jalium.native.text/include/jalium_emoji_data.h')
    parser.add_argument('--managed-out',type=Path,default=ROOT/'src/managed/Jalium.UI.Core/Css/CssEmojiData.cs')
    args=parser.parse_args();sources={name:(args.data_dir/name).read_bytes() if args.data_dir else urllib.request.urlopen(BASE+name,timeout=30).read() for name in HASHES}
    native,managed,sets=generate(sources);args.native_out.write_text(native);args.managed_out.write_text(managed)
    print(f"Unicode {VERSION}: {len(sets['Participating'])} participating points, {len(sets['DefaultEmoji'])} emoji-default participating points")

if __name__=='__main__':main()
