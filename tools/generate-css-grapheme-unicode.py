#!/usr/bin/env python3
"""Generate native UAX #29 properties from pinned Unicode 17 inputs."""
from pathlib import Path
import hashlib,json
root=Path(__file__).resolve().parents[1];base=root/'src/native/thirdparty/unicode-grapheme-17'
manifest=json.loads((base/'UPSTREAM.json').read_text());assert manifest['unicode_version']=='17.0.0'
for row in manifest['inputs']:assert hashlib.sha256((base/row['file']).read_bytes()).hexdigest()==row['sha256'],row['file']
values=bytearray(0x110000)
properties=['Other','CR','LF','Control','Extend','ZWJ','Regional_Indicator','Prepend','SpacingMark','L','V','T','LV','LVT']
def entries(name):
 for line in (base/name).read_text().splitlines():
  data=line.split('#',1)[0].strip()
  if not data:continue
  fields=[x.strip()for x in data.split(';')];limits=fields[0].split('..');yield int(limits[0],16),int(limits[-1],16),fields[1:]
for first,last,fields in entries('GraphemeBreakProperty.txt'):
 value=properties.index(fields[0]);values[first:last+1]=bytes([value])*(last-first+1)
for first,last,fields in entries('emoji-data.txt'):
 if fields[0]=='Extended_Pictographic':
  for cp in range(first,last+1):values[cp]|=16
for first,last,fields in entries('DerivedCoreProperties.txt'):
 if fields[0]=='InCB':
  flag={'Linker':32,'Consonant':64,'Extend':96}[fields[1]]
  for cp in range(first,last+1):values[cp]|=flag
rows=[];first=0
for cp in range(1,len(values)+1):
 if cp==len(values)or values[cp]!=values[first]:
  if values[first]:rows.append((first,cp-1,values[first]))
  first=cp
text='// Generated by tools/generate-css-grapheme-unicode.py; Unicode 17.0.0.\n// Data license: Unicode-3.0, src/native/thirdparty/UNICODE-LICENSE.txt.\n#pragma once\n#include <cstdint>\nnamespace jalium::grapheme {\nstruct PropertyRange { uint32_t first, last; uint8_t value; };\ninline constexpr PropertyRange kProperties[] = {\n'
text+=''.join(f'    {{0x{a:X}, 0x{b:X}, {v}}},\n'for a,b,v in rows)+'};\n} // namespace jalium::grapheme\n'
output=root/'src/native/jalium.native.text/include/unicode_grapheme_data.h';output.write_text(text);print(len(rows),'property ranges')
