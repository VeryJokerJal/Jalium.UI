"""Generate portable Unicode casing tables shared by native CSS text paths.

Use --data-dir for an offline, pinned UCD directory. The Unicode version matches
the managed CSS special-casing/context generators; no runtime dependency is added.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import urllib.request
from pathlib import Path


VERSION = "18.0.0"
BASE = f"https://www.unicode.org/Public/{VERSION}/ucd/"
OUTPUT = Path(__file__).resolve().parents[1] / "src/native/jalium.native.text/include/jalium_unicode_casing_data.h"
ENTRY = re.compile(r"^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*([A-Za-z_]+)", re.M)


def property_set(source: str, name: str) -> set[int]:
    values: set[int] = set()
    for match in ENTRY.finditer(source):
        if match[3] == name:
            values.update(range(int(match[1], 16), int(match[2] or match[1], 16) + 1))
    if not values:
        raise ValueError(f"Missing Unicode property: {name}")
    return values


def ranges(values: set[int]) -> list[tuple[int, int]]:
    result: list[tuple[int, int]] = []
    for value in sorted(values):
        if result and value == result[-1][1] + 1:
            result[-1] = result[-1][0], value
        else:
            result.append((value, value))
    return result


def generate(sources: dict[str, bytes]) -> str:
    data = {name: value.decode("utf-8") for name, value in sources.items()}
    for name in ["DerivedCoreProperties.txt", "PropList.txt", "SpecialCasing.txt"]:
        if f"-{VERSION}.txt" not in data[name].splitlines()[0]:
            raise ValueError(f"Expected Unicode {VERSION} input: {name}")
    maps: dict[str, dict[int, tuple[int, ...]]] = {"Lower": {}, "Upper": {}}
    above: set[int] = set()
    other: set[int] = set()
    title: set[int] = set()
    for line in data["UnicodeData.txt"].splitlines():
        fields = line.split(";")
        codepoint = int(fields[0], 16)
        if fields[2] == "Lt":
            title.add(codepoint)
        combining = int(fields[3])
        if combining == 230:
            above.add(codepoint)
        elif combining:
            other.add(codepoint)
        for name, index in [("Lower", 13), ("Upper", 12)]:
            if fields[index]:
                maps[name][codepoint] = (int(fields[index], 16),)
    for line in data["SpecialCasing.txt"].splitlines():
        fields = line.split("#", 1)[0].split(";")
        if len(fields) < 5 or fields[4].strip():
            continue  # Conditional rules use the complete source context.
        codepoint = int(fields[0], 16)
        for name, index in [("Lower", 1), ("Upper", 3)]:
            maps[name][codepoint] = tuple(int(v, 16) for v in fields[index].split())
    properties = {
        "Lowercase": property_set(data["DerivedCoreProperties.txt"], "Lowercase"),
        "Uppercase": property_set(data["DerivedCoreProperties.txt"], "Uppercase") | title,
        "Cased": property_set(data["DerivedCoreProperties.txt"], "Cased"),
        "CaseIgnorable": property_set(data["DerivedCoreProperties.txt"], "Case_Ignorable"),
        "SoftDotted": property_set(data["PropList.txt"], "Soft_Dotted"),
        "Above": above,
        "OtherCombining": other,
    }
    lines = [
        "// Generated by tools/generate-css-native-casing.py. Do not edit.",
        f"// Unicode {VERSION}: {BASE}",
        "// Unicode data © 2026 Unicode, Inc. https://www.unicode.org/terms_of_use.html",
        *[f"// SHA-256 {name}: {hashlib.sha256(value).hexdigest()}" for name, value in sorted(sources.items())],
        "#pragma once", "#include <cstddef>", "#include <cstdint>", "",
        "namespace jalium::unicode_casing::data {",
        "struct Range { uint32_t first, last; };",
        "struct Mapping { uint32_t codepoint, offset; uint16_t length; };", "",
    ]
    for name, values in properties.items():
        lines.append(f"inline constexpr Range {name}[] = {{")
        pairs = ranges(values)
        for index in range(0, len(pairs), 4):
            lines.append("    " + " ".join(f"{{0x{first:X}, 0x{last:X}}}," for first, last in pairs[index:index + 4]))
        lines.extend(["};", ""])
    for name, values in maps.items():
        text: list[int] = []
        entries = []
        for codepoint, target in sorted(values.items()):
            if target == (codepoint,):
                continue
            encoded = "".join(chr(v) for v in target).encode("utf-16-le")
            units = [int.from_bytes(encoded[i:i + 2], "little") for i in range(0, len(encoded), 2)]
            entries.append((codepoint, len(text), len(units)))
            text.extend(units)
        lines.append(f"inline constexpr char16_t {name}Text[] =")
        for index in range(0, len(text), 16):
            lines.append('    u"' + "".join(f"\\x{v:04X}" for v in text[index:index + 16]) + '"')
        lines.extend(["    ;", f"inline constexpr Mapping {name}Map[] = {{"])
        for index in range(0, len(entries), 4):
            lines.append("    " + " ".join(f"{{0x{cp:X}, {at}, {count}}}," for cp, at, count in entries[index:index + 4]))
        lines.extend(["};", ""])
    lines.extend(["} // namespace jalium::unicode_casing::data", ""])
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-dir", type=Path)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()
    sources = {}
    for name in ["UnicodeData.txt", "DerivedCoreProperties.txt", "PropList.txt", "SpecialCasing.txt"]:
        sources[name] = (args.data_dir / name).read_bytes() if args.data_dir else urllib.request.urlopen(BASE + name).read()
    args.output.write_text(generate(sources), encoding="utf-8")


if __name__ == "__main__":
    main()
