#!/usr/bin/env python3
"""Generate the shared UAX #50 tables from pinned Unicode 18 input."""
from pathlib import Path
import hashlib
import json

root = Path(__file__).resolve().parents[1]
base = root / 'src/native/thirdparty/unicode-vertical-18'
manifest = json.loads((base / 'UPSTREAM.json').read_text())
assert manifest['unicode_version'] == '18.0.0'
for item in manifest['inputs']:
    assert hashlib.sha256((base / item['file']).read_bytes()).hexdigest() == item['sha256'], item['file']

values = bytearray(0x110000)
enclosing = bytearray(len(values))
properties = {'R': 0, 'U': 1, 'Tu': 2, 'Tr': 3}
for line in (base / 'VerticalOrientation.txt').read_text().splitlines():
    data, _, comment = line.partition('#')
    if not data.strip():
        continue
    codepoints, property = [part.strip() for part in data.split(';')]
    limits = codepoints.split('..')
    first, last = int(limits[0], 16), int(limits[-1], 16)
    values[first:last + 1] = bytes([properties[property]]) * (last - first + 1)
    # UAX #50 gives a cluster containing a general-category Me character
    # the upright orientation, including keycaps whose first scalar is R.
    if comment.split()[0] == 'Me':
        enclosing[first:last + 1] = b'\1' * (last - first + 1)


def ranges(data):
    result = []
    first = 0
    for point in range(1, len(data) + 1):
        if point == len(data) or data[point] != data[first]:
            if data[first]:
                result.append((first, point - 1, data[first]))
            first = point
    return result


rows = ranges(values)
marks = ranges(enclosing)
header = '// Generated by tools/generate-css-vertical-orientation.py; Unicode 18.0.0.\n'
header += '// Data license: Unicode-3.0, src/native/thirdparty/UNICODE-LICENSE.txt.\n'
native = header + '#pragma once\n#include <cstddef>\n#include <cstdint>\nnamespace jalium::vertical_orientation {\n'
native += '// 0=R, 1=U, 2=Tu, 3=Tr. The default is R.\nstruct Range { uint32_t first, last; uint8_t value; };\n'
for name, entries in [('Properties', rows), ('EnclosingMarks', marks)]:
    native += f'inline constexpr Range {name}[] = {{\n'
    native += ''.join(f'    {{0x{a:X}, 0x{b:X}, {v}}},\n' for a, b, v in entries)
    native += '};\n'
native += '''template<size_t N> inline uint8_t Find(const Range (&ranges)[N], uint32_t scalar) {
    size_t first = 0, last = N;
    while (first < last) {
        const size_t mid = first + (last - first) / 2;
        if (scalar < ranges[mid].first) last = mid;
        else if (scalar > ranges[mid].last) first = mid + 1;
        else return ranges[mid].value;
    }
    return 0;
}
inline uint8_t Property(uint32_t scalar) { return Find(Properties, scalar); }
inline bool Enclosing(uint32_t scalar) { return Find(EnclosingMarks, scalar) != 0; }
} // namespace jalium::vertical_orientation
'''
(root / 'src/native/jalium.native.text/include/unicode_vertical_orientation_data.h').write_text(native)

managed = header + 'namespace Jalium.UI.Styling;\n\ninternal static class CssUnicodeVerticalOrientationData\n{\n'
for name, entries in [('Properties', rows), ('EnclosingMarks', marks)]:
    managed += f'    private static readonly (int First, int Last, byte Value)[] {name} =\n    [\n'
    managed += ''.join(f'        (0x{a:X}, 0x{b:X}, {v}),\n' for a, b, v in entries)
    managed += '    ];\n\n'
managed += '''    internal static byte Property(int scalar) => Find(Properties, scalar);
    internal static bool Enclosing(int scalar) => Find(EnclosingMarks, scalar) != 0;

    private static byte Find((int First, int Last, byte Value)[] ranges, int scalar)
    {
        int first = 0, last = ranges.Length;
        while (first < last)
        {
            int mid = first + (last - first) / 2;
            if (scalar < ranges[mid].First) last = mid;
            else if (scalar > ranges[mid].Last) first = mid + 1;
            else return ranges[mid].Value;
        }
        return 0;
    }
}
'''
(root / 'src/managed/Jalium.UI.Core/Css/CssUnicodeVerticalOrientationData.cs').write_text(managed)
print(f'{len(rows)} orientation ranges; {len(marks)} enclosing-mark ranges')
